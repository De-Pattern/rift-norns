"""Write the machine definitions both sides read, from DN2-Rift's panel tables (machines.py):
    ignore/RiftNorns/RiftNorns.sc   the five UGen classes (control names, MACHINE SEL defaults)
    lib/machines.lua                pages, labels, choices and boxes, defaults, MIDI CCs, LIGATURE's wiring

    PYTHONPATH=../DN2-Rift/src python3 ignore/dev/tools/gen_machines.py
"""
from pathlib import Path

from dnfw.fascia import machines as FM
from dnfw.fascia import model as FMOD
from dnfw.ligature import live as GL
from dnfw.ligature import machines as GM
from dnfw.organ import machines as OM
from dnfw.reson import machines as RM
from dnfw.silt import live as SL
from dnfw.silt import machines as SM

ROOT = Path(__file__).resolve().parents[3]

# FASCIA's MIDI CCs: RIFT's, and 102..111 for the ten records without one. Every other machine
# rides FASCIA's records, so a control's CC is the CC of the FASCIA control it rides.
FCC = {"TYPA": 41, "TYPB": 45, "HARD": 43, "DUST": 102, "TZFM": 103, "BEND": 104, "MIX": 105, "DEC": 56,
       "BODA": 42, "BODB": 46, "TUNE": 47, "GEOM": 106, "MATL": 107, "POS": 108, "COUP": 109, "DAMP": 57,
       "MORPH": 55, "FORM": 58, "SHIFT": 61, "RING": 110, "SIDE": 72, "FOLD": 71, "LPG": 59, "CHAR": 63,
       "ATK": 75, "CLIK": 60, "CTYP": 52, "XMOD": 48, "FDBK": 76, "BUZZ": 111, "WATR": 70, "VARY": 77}


def mid(n, k):
    """the knob in the middle of option k's span (as RIFT's choice() reads it)"""
    return ((2 * k + 1) * 64) // n


def fascia_defaults():
    return {c: FMOD.DEFAULTS[c] for c in FMOD.INTERNAL}


def silt_defaults():
    d = dict(SM.KNOB_DEFAULTS)
    for c, o in SM.OPT_DEFAULTS.items():
        d[c] = SL.option_knob(o, len(SM.CHOICES[c]))
    return d


def lig_defaults():
    d = dict(GM.KNOB_DEFAULTS)
    d["PATCH"] = mid(len(GM.CHOICES["PATCH"]), GM.OPT_DEFAULTS["PATCH"])
    return d


def organ_defaults():
    return dict(OM.DEFAULTS)


MACHINES = [
    # id, name, ugen, module, defaults, rides, voices, note-off ('none' rings on, 'gate' its own, 'release')
    ("fascia", "FASCIA", "RiftFascia", FM, fascia_defaults(), {c: c for c in FMOD.INTERNAL}, 6, "none"),
    ("organ", "ORGAN", "RiftOrgan", OM, organ_defaults(), OM.RIDES, 6, "release"),
    ("silt", "SILT", "RiftSilt", SM, silt_defaults(), SM.RIDES, 4, "gate"),
    ("ligature", "LIGATURE", "RiftLigature", GM, lig_defaults(), GM.RIDES, 6, "gate"),
    ("resonator", "RESONATOR", "RiftResonator", RM, dict(RM.KNOB_DEFAULTS), RM.RIDES, 6, "none"),
]


def controls(mod):
    return [c for page in mod.PAGES.values() for c in page]


def sc_name(c):
    return "rn" + c.lower()


def lua_str(s):
    return '"' + s.replace('"', '\\"') + '"'


def write_sc():
    out = ["// Generated by ignore/dev/tools/gen_machines.py from DN2-Rift's panel tables. Do not edit.",
           "// RIFT's machines, one voice a UGen: X.ar(trig, note, vel, seed, kill, gate, rel, bpm, *controls).",
           "// The controls are 0..127 in RIFT's page order (X.names; lower case with rn, so a SynthDef's",
           "// control names never read as class names or rate prefixes); X.defaults is what MACHINE SEL writes."]
    for mid_, name, ugen, mod, dflt, _r, _v, _o in MACHINES:
        cs = controls(mod)
        names = ", ".join("\\" + sc_name(c) for c in cs)
        defs = ", ".join(str(int(dflt[c])) for c in cs)
        out.append(f"""
{ugen} : UGen {{
	*names {{ ^#[{names}] }}
	*defaults {{ ^#[{defs}] }}
	*ar {{ arg trig = 1, note = 60, vel = 1, seed = 1, kill = 0, gate = 1, rel = 0.1, bpm = 120 ... controls;
		var c = controls.flat;
		if(c.size != {len(cs)}) {{ c = this.defaults.collect {{ |d, i| c[i] ? d }} }};
		^this.multiNewList(['audio', trig, note, vel, seed, kill, gate, rel, bpm] ++ c)
	}}
}}""")
    (ROOT / "ignore/RiftNorns/RiftNorns.sc").write_text("\n".join(out) + "\n")


def write_lua():
    o = ["-- Generated by ignore/dev/tools/gen_machines.py from DN2-Rift's panel tables. Do not edit.",
         "-- Every machine: its pages (RIFT's), each control's label, long name, choices (names and the",
         "-- four-letter boxes), bipolar, MACHINE SEL default (0..127), MIDI CC and SynthDef name.",
         "local M = {}"]
    for mid_, name, ugen, mod, dflt, rides, voices, off in MACHINES:
        cs = controls(mod)
        labels = getattr(mod, "LABELS", {})
        longs = getattr(mod, "LONG_NAMES", {})
        box = getattr(mod, "BOX", {})
        bip = set(getattr(mod, "BIPOLAR", ()))
        ch = getattr(mod, "CHOICES", {})
        pages = []
        for t, row in mod.PAGES.items():
            title = t.split(" ", 1)[1] if t.startswith("SYN") else t
            pages.append("{title = " + lua_str(title) + ", controls = {" + ", ".join(lua_str(c) for c in row) + "}}")
        o.append(f"M[#M + 1] = {{id = {lua_str(mid_)}, name = {lua_str(name)}, ugen = {lua_str(ugen)}, "
                 f"voices = {voices}, off = {lua_str(off)},")
        o.append("  pages = {\n    " + ",\n    ".join(pages) + "},")
        o.append("  order = {" + ", ".join(lua_str(c) for c in cs) + "},")
        o.append("  ctl = {")
        for c in cs:
            parts = [f"label = {lua_str(labels.get(c, c))}", f"long = {lua_str(longs.get(c, c).upper())}",
                     f"default = {int(dflt[c])}", f"cc = {FCC[rides[c]]}", f"sc = {lua_str(sc_name(c))}"]
            if c in bip:
                parts.append("bipolar = true")
            if c in ch:
                parts.append("choices = {" + ", ".join(lua_str(x) for x in ch[c]) + "}")
                parts.append("box = {" + ", ".join(lua_str(box.get(x, x)[:4]) for x in ch[c]) + "}")
            o.append(f"    [{lua_str(c)}] = {{" + ", ".join(parts) + "},")
        o.append("  },")
        o.append("}")
    # LIGATURE's wiring: each patch's blocks (type, A source and amount, B source and amount), its out
    tn = GL.TYPE_NAMES
    o.append("-- LIGATURE's patches: 12 blocks (type, A, amount A, B, amount B; a source 1..12 is a block,")
    o.append("-- 13..19 PITCH GATE TRIG VEL NOISE LFO1 LFO2), the block that is the voice's output, and")
    o.append("-- BMOVE (blocks whose B moves setting 2)")
    o.append("M.wiring = {")
    for k in range(GL.NP):
        rows, outb, bm = GL.patch_rows(k)
        rs = []
        for (ty, a, aa, b, ab, d1, d2) in rows:
            if ty == GL.NONE:
                rs.append("false")
            else:
                rs.append(f"{{type = {lua_str(tn[ty])}, a = {a}, aa = {aa}, b = {b}, ab = {ab}, d1 = {d1}, d2 = {d2}}}")
        o.append(f"  {{name = {lua_str(GL.PATCHES[k][0])}, out = {outb}, bm = {bm}, blocks = {{" + ", ".join(rs) + "}},")
    o.append("}")
    o.append('M.sources = {[13] = "PIT", [14] = "GAT", [15] = "TRG", [16] = "VEL", [17] = "NOI", [18] = "LF1", [19] = "LF2"}')
    o.append("return M")
    (ROOT / "lib/machines.lua").write_text("\n".join(o) + "\n")


if __name__ == "__main__":
    write_sc()
    write_lua()
    print("wrote ignore/RiftNorns/RiftNorns.sc and lib/machines.lua")
