"""Generate src/fascia_tables.h from RIFT's FASCIA reference (dnfw.fascia.live / model).

    PYTHONPATH=../DN2-Rift/src python3 ignore/dev/tools/gen_tables.py > ignore/src/fascia_tables.h

Every constant is written as a C hex float of the exact float32 the reference uses, so the
C++ port computes with the same bits as live.py.
"""
import math
import sys

import numpy as np

from dnfw.fascia import live as L
from dnfw.fascia import model as M

F = np.float32


def hx(x) -> str:
    v = float(F(x))
    if v == 0.0:
        return "0.0f"
    return float.hex(v) + "f"


def arr(name, xs):
    xs = [hx(x) for x in xs]
    rows = [", ".join(xs[i:i + 6]) for i in range(0, len(xs), 6)]
    return f"static const float {name}[{len(xs)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


out = []
w = out.append
w("// Generated by ignore/dev/tools/gen_tables.py from DN2-Rift's src/dnfw/fascia (live.py, model.py).\n")
w("// Do not edit: regenerate.\n#pragma once\n\nnamespace fascia {\n")

R = L.RATE
consts = {
    "LOG2E": L.LOG2E, "INV127": L.INV127, "INVR": L.INVR, "SQ15": L._SQ15,
    "C_DECAY": L.C_DECAY, "F_HI": L.F_HI, "F_LO": L.F_LO, "H_SCALE": L.H_SCALE,
    "TANH_TOP": L.TANH_TOP, "TOPT": L._TOP, "IDLE": L.IDLE, "OUTL": L.OUT, "FLOORF": F(L.FLOOR),
    "GUARD": F(L.GUARD),
    "K_RAMP": L.K_RAMP, "K_PE": L.K_PE, "BOW_LO": L.BOW_LO, "BOW_HI": L.BOW_HI,
    "LIM_TH": L.LIM_TH, "LIM_KR": L.LIM_KR, "DC_A": L.DC_A, "K_CHIRP": L.K_CHIRP, "SQ2": L.SQ2,
    "W_KA1": L.Water.KA1, "W_KR1": L.Water.KR1, "W_KA2": L.Water.KA2, "W_KR2": L.Water.KR2,
    "W_GMAX": L.Water.GMAX, "FADE_STEP": L.FADE_STEP,
    "LOG2_440F": F(L.LOG2_440), "INV12": F(1.0 / 12.0), "INVBLOCK": F(1.0 / L.BLOCK),
    # expmap's log2(hi/lo)
    "LG_DUST": F(math.log2(3000.0 / 5.0)), "LG_GRIT": F(math.log2(4000.0 / 20.0)),
    "LG_ATK": F(math.log2(0.5 / 0.0002)), "LG_DEC": F(math.log2(2.0 / 0.004)),
    # onepole_inv's exponent scale for 1 and BLOCK samples
    "OP1": F(-1 * (1.0 / math.log(2.0)) / R), "OP32": F(-L.BLOCK * (1.0 / math.log(2.0)) / R),
    "LG_WIDTH": F(math.log2(0.0125)), "LG_30": F(math.log2(30.0)),
    "BLOW_W": F(-2.0 * math.pi / math.log(2.0) / R), "LG_400": F(math.log2(400.0)),
    "INV_003": F(1.0 / 0.03), "HALF_PI": F(math.pi / 2), "INV63": F(1.0 / 63.0),
    "INV_2PI": F(1.0 / (2 * math.pi)), "LG_WATER": F(math.log2(9000.0 / 2.2)),
    "WATER_TOP": F(0.4 * R), "SQRT_HALF": F(math.sqrt(0.5)), "PHI_SCALE": F(4.0 / M.OUT),
    "INV_15": F(1.0 / 1.5), "HANN_VARF": F(L.HANN_VAR), "DSIG": F(math.sqrt(3.0) * 1.5e-5),
    "INV_035": F(1.0 / 0.35), "THIRD": F(1.0 / 3.0), "INV16": F(1.0 / 16.0),
    "KH_BOW": F(math.exp(-1.0 / (0.08 * R))), "KH_BLOW": F(math.exp(-1.0 / (0.06 * R))),
    "KP_THUMP": F(math.exp(-1.0 / (0.008 * R))),
}
for k, v in consts.items():
    w(f"static const float {k} = {hx(v)};\n")
w("\n")
for k in range(16):
    w(f"// js[{k}]\n") if False else None
w(arr("JS", [math.sqrt(3.0) * 0.0012 * (1.0 + 0.15 * k) for k in range(16)]))
w(arr("WK7", [k / 7.0 for k in range(8)]))
w(arr("EXP2_C", L.EXP2_C))
w(arr("SIN_C", L.SIN_C))
w(arr("COS_C", L.COS_C))
w(arr("EXPM1_C", L.EXPM1_C))
w(arr("TANH_N", L.TANH_N))
w(arr("TANH_D", L.TANH_D))
w(arr("SIN_T", L.SIN_T))
SA2, SB2 = L._shift_coeffs()
w(arr("SH_A2", SA2))
w(arr("SH_B2", SB2))
w(arr("VOWELS", [x for pair in M.VOWELS for x in pair]))

# bodies, in model.BODIES order (OFF last)
bodies = M.BODIES[:-1]
w(f"static const int NBODY = {len(bodies)};\n")
w("static const char *const BODY_NAMES[10] = {" + ", ".join(f'"{b}"' for b in M.BODIES) + "};\n")
w("static const char *const TYPE_NAMES[6] = {" + ", ".join(f'"{b}"' for b in M.TYPES) + "};\n")
w("static const char *const CLICK_NAMES[4] = {" + ", ".join(f'"{b}"' for b in M.CLICKS) + "};\n")
w("static const char *const XMOD_NAMES[4] = {" + ", ".join(f'"{b}"' for b in M.XMODS) + "};\n")
w("static const float LOG2R[9][16] = {\n" + ",\n".join(
    "  {" + ", ".join(hx(x) for x in L.LOG2R[b]) + "}" for b in bodies) + "\n};\n")
w(arr("SPATIAL", [M.SPATIAL[b] for b in bodies]))
w(arr("SPLIT", [M.SPLIT[b] for b in bodies]))
w(arr("BEAT_MAX", [M.BEAT_MAX[b] for b in bodies]))
w(arr("RING_BIAS", [M.RING_BIAS[b] for b in bodies]))
w(arr("B_RATIO", [M.B_RATIO.get(b, 1.0) for b in M.BODIES]))
cw = M.MODE_WEIGHT["CHIME"]
w(arr("CHIME_W", cw))
w(f"static const int BODY_CHIME = {bodies.index('CHIME')};\n")
w(arr("TYPE_GAIN", [M.TYPE_GAIN[t] for t in M.TYPES]))

names = list(M.INTERNAL)
w("enum Param {\n  " + ", ".join(f"P_{n}" for n in names) + ", NPARAM\n};\n")
w("static const char *const PARAM_NAMES[NPARAM] = {" + ", ".join(f'"{n}"' for n in names) + "};\n")
w("static const int INTERNAL_DEFAULTS[NPARAM] = {" + ", ".join(str(M.INTERNAL[n]) for n in names) + "};\n")
w("static const int PANEL_DEFAULTS[NPARAM] = {" + ", ".join(str(M.DEFAULTS[n]) for n in names) + "};\n")
w("\n}  // namespace fascia\n")
sys.stdout.write("".join(out))
