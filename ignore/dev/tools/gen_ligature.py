"""Write ignore/src/ligature_tables.h: LIGATURE's WEFT patches, block names and mode constants,
exactly as DN2-Rift's ligature/live.py has them.
    PYTHONPATH=../DN2-Rift/src python3 ignore/dev/tools/gen_ligature.py > ignore/src/ligature_tables.h"""
import numpy as np
from dnfw.ligature import live as G
hx = lambda v: float.hex(float(np.float32(v))) + "f"
o = ["// Generated by ignore/dev/tools/gen_ligature.py from DN2-Rift's ligature/live.py.",
     "#pragma once\n#include <cstdint>\nnamespace ligature {", f"static const int NP = {G.NP};"]
o.append("struct PatchRow { int16_t ty, a, aa, b, ab, d1, d2; };")
o.append("struct Patch { const char *name; PatchRow rows[12]; int out; int bm; };")
o.append("static const Patch PATCHES[NP] = {")
for k in range(G.NP):
    rows, out, bm = G.patch_rows(k)
    rs = ", ".join("{" + ", ".join(str(int(x)) for x in r) + "}" for r in rows)
    o.append(f'  {{"{G.PATCHES[k][0]}", {{{rs}}}, {out}, {bm}}},')
o.append("};")
o.append("static const float RATIO[16] = {" + ", ".join(hx(x) for x in G.RATIO) + "};")
for t, nm in ((G.SKIN, "SKIN"), (G.BAR, "BAR")):
    o.append(f"static const float MODES_{nm}[6] = {{" + ", ".join(hx(x) for x in G.MODES[t]) + "};")
    o.append(f"static const float L2REL_{nm}[6] = {{" + ", ".join(hx(x) for x in G.L2REL[t]) + "};")
o.append("static const float L2K[6] = {" + ", ".join(hx(x) for x in G.L2K) + "};")
for n in ("INV16",):
    o.append(f"static const float {n} = {hx(getattr(G, n))};")
o.append("}")
print("\n".join(o))
